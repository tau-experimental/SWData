// Функция быстрой побитовой инверсии 8-битного индекса для БПФ-256
static inline uint8_t bit_reverse8(uint8_t x) {
    x = ((x & 0xF0) >> 4) | ((x & 0x0F) << 4);
    x = ((x & 0xCC) >> 2) | ((x & 0x33) << 2);
    x = ((x & 0xAA) >> 1) | ((x & 0x55) << 1);
    return x;
}

// Вычисление Fixed-Point БПФ-256 (In-Place)
// io_buffer: массив из 256 комплексных чисел int16, который перезаписывается спектром
void fft256_fixed_point(cplx_i16 *io_buffer)
{
    int i, j, k;

    // 1. Битовая инверсия (Bit Reversal Перестановка)
    for (i = 0; i < 256; i++) {
        j = bit_reverse8(i);
        if (i < j) {
            cplx_i16 temp = io_buffer[i];
            io_buffer[i] = io_buffer[j];
            io_buffer[j] = temp;
        }
    }

    // 2. Основной цикл Кули-Тьюки (8 каскадов для N=256)
    int log2n = 8;
    int le = 1; // длина текущего подблока

    for (int stage = 0; stage < log2n; stage++) {
        int le_next = le << 1;
        int twiddle_step = 128 >> stage; // шаг по таблице поворотных коэффициентов

        for (j = 0; j < le; j++) {
            // Берем поворотный коэффициент из Flash таблицы
            cplx_i16 w = twiddle_256[j * twiddle_step];

            for (i = j; i < 256; i += le_next) {
                int ip = i + le;

                // Комплексное умножение бабочки: t = io_buffer[ip] * w (в формате Q15)
                int32_t t_re = ((int32_t)io_buffer[ip].re * w.re) - ((int32_t)io_buffer[ip].im * w.im);
                int32_t t_im = ((int32_t)io_buffer[ip].im * w.re) + ((int32_t)io_buffer[ip].re * w.im);

                cplx_i16 t;
                t.re = (int16_t)(t_re >> 15);
                t.im = (int16_t)(t_im >> 15);

                // Бабочка с ОДНОВРЕМЕННЫМ масштабированием (>> 1) против переполнения!
                io_buffer[ip].re = (io_buffer[i].re - t.re) >> 1;
                io_buffer[ip].im = (io_buffer[i].im - t.im) >> 1;
                io_buffer[i].re  = (io_buffer[i].re + t.re) >> 1;
                io_buffer[i].im  = (io_buffer[i].im + t.im) >> 1;
            }
        }
        le = le_next;
    }
}
