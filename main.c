#include <stdio.h>
#include <string.h>
#include "puncturing.h"

int main(void) {
    unsigned char tx_bits_1_2[1680];
    unsigned char bits_5_6[1008];
    unsigned char rx_soft_bits_1_2[1680];
    int i;
    int success = 1;

    printf("==============================================================================$$\n");
    printf("        ЗАПУСК ИЗОЛИРОВАННОГО ЮНИТ-ТЕСТА МОДУЛЯ ВЫКАЛЫВАНИЯ (PUNCTURING)\n");
    printf("==============================================================================$$\n\n");

    /* 1. Генерируем тестовый паттерн: чередующиеся 0 и 1 */
    for (i = 0; i < 1680; i++) {
        tx_bits_1_2[i] = (unsigned char)(i % 2);
    }

    /* 2. Выполняем выкалывание (Tx сторона) */
    apply_puncturing(tx_bits_1_2, bits_5_6);
    printf("[TX] Выкалывание выполнено успешно. 1680 бит сжаты в 1008 бит.\n");

    /* 3. Выполняем депунктурирование (Rx сторона в стерильном канале) */
    apply_depuncturing(bits_5_6, rx_soft_bits_1_2);
    printf("[RX] Депунктурирование выполнено успешно. Получено 1680 мягких отсчетов.\n\n");

    /* 4. ТОТАЛЬНЫЙ ПОБИТОВЫЙ АУДИТ МАТРИЦЫ */
    printf("=== АНАЛИЗ ПЕРВОГО 10-БИТНОГО БЛОКА ===\n");
    printf("Индекс | Исходный бит | Мягкое решение на приеме | Статус\n");
    printf("-----------------------------------------------------------\n");
    for (i = 0; i < 10; i++) {
        printf("  %03d  |       %d      |            %3d           | ",
               i, tx_bits_1_2[i], rx_soft_bits_1_2[i]);

        /* Проверяем позиции, которые должны быть выколоты */
        if (i == 3 || i == 5 || i == 7 || i == 9) {
            if (rx_soft_bits_1_2[i] == 127) {
                printf("УСПЕХ: Выколотый бит заменен на 127\n");
            } else {
                printf("ОШИБКА: Ожидался маркер 127!\n");
                success = 0;
            }
        }
        /* Проверяем выжившие рабочие биты */
        else {
            unsigned char expected_hard = tx_bits_1_2[i] ? 255 : 0;
            if (rx_soft_bits_1_2[i] == expected_hard) {
                printf("УСПЕХ: Бит доставлен без искажений\n");
            } else {
                printf("ОШИБКА: Бит поврежден при трансляции!\n");
                success = 0;
            }
        }
    }
    printf("-----------------------------------------------------------\n");

    /* 5. Сквозная проверка всех остальных 168 блоков в массиве */
    for (i = 0; i < 1680; i++) {
        int sub_idx = i % 10;
        if (sub_idx == 3 || sub_idx == 5 || sub_idx == 7 || sub_idx == 9) {
            if (rx_soft_bits_1_2[i] != 127) success = 0;
        } else {
            unsigned char expected_hard = tx_bits_1_2[i] ? 255 : 0;
            if (rx_soft_bits_1_2[i] != expected_hard) success = 0;
        }
    }

    printf("\n==============================================================================$$\n");
    if (success) {
        printf("  [ВЕРДИКТ] ИЗОЛИРОВАННЫЙ ТЕСТ PUNCTURING ПРОЙДЕН СО 100%% ТОЧНОСТЬЮ!\n");
        printf("  Индексы выкалывания идеальны. Модуль канонизирован и готов к фиксации.\n");
    } else {
        printf("  [ВЕРДИКТ] КРИТИЧЕСКАЯ ОШИБКА МАТЕМАТИКИ ИНДЕКСОВ. Модуль забракован.\n");
    }
    printf("==============================================================================$$\n");

    return success ? 0 : 1;
}
