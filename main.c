#include <stdio.h>
#include <string.h>
#include "conv_encoder.h"

int main(void) {
    conv_encoder_t encoder;
    unsigned char tx_bytes[105];
    unsigned char output_dibits[504];
    unsigned char rx_bytes[105];
    int i;
    int success = 1;

    printf("==============================================================================$$\n");
    printf("        ЗАПУСК СТРЕСС-ТЕСТА 2.4c: ПРОВЕРКА ПОМЕХОУСТОЙЧИВОСТИ ДЕКОДЕРА ВИТЕРБИ\n");
    printf("==============================================================================$$\n\n");

    /* 1. Генерируем эталонные тестовые данные */
    for (i = 0; i < 104; i++) {
        tx_bytes[i] = (unsigned char)(i * 3 + 7);
    }
    tx_bytes[104] = 0x00; /* Хвост кодера */

    /* 2. Штатное кодирование (Tx) */
    conv_encoder_reset(&encoder);
    conv_encode_block(&encoder, tx_bytes, 105, output_dibits);

    /* ------------------------------------------------------------------------- */
    /* СЦЕНАРИЙ 1: Помеха в канале (Проверка исправления ошибок)                */
    /* ------------------------------------------------------------------------- */
    printf("[ТЕСТ 1] Наводим помеху: инвертируем дибиты в канале (имитируем шум)...\n");

    /* Искажаем несколько дибитов в разных частях пакета */
    /* Инвертируем биты через XOR маску 0x03 (означает, что вылетели оба бита символа) */
    output_dibits[10] ^= 0x03;
    output_dibits[50] ^= 0x03;
    output_dibits[120] ^= 0x03;
    output_dibits[300] ^= 0x03;
    output_dibits[450] ^= 0x03;

    printf("[RX] Запуск декодера Витерби в условиях шума...\n");
    viterbi_decode_block(rx_bytes, output_dibits);

    /* Верификация */
    if (memcmp(tx_bytes, rx_bytes, 105) == 0) {
        printf(">> [УСПЕХ] Декодер Витерби полностью исправил изолированные ошибки в канале!\n");
        printf(">> [УСПЕХ] Данные на выходе совпали с исходными на 100%%.\n\n");
    } else {
        printf(">> [ПРОВАЛ] Декодер не справился с шумом. Данные искажены!\n");
        printf("\n=== ПОБАЙТОВЫЙ АНАЛИЗ ИСКАЖЕНИЙ ДАННЫХ (TX vs RX) ===\n");
        printf("Индекс | Исходный (TX) | Полученный (RX) | XOR Маска ошибки (Биты)\n");
        printf("-------------------------------------------------------------------\n");
        for (i = 0; i < 20; i++) { /* Смотрим первые 20 байт */
            unsigned char diff = tx_bytes[i] ^ rx_bytes[i];
            printf("  %03d  |     0x%02X      |      0x%02X      |       0x%02X  ", i, tx_bytes[i], rx_bytes[i], diff);
            if (diff != 0) {
                printf(" <-- ИСКАЖЕН!");
            }
            printf("\n");
        }
        printf("-------------------------------------------------------------------\n\n");
        success = 0;
    }

    /* ------------------------------------------------------------------------- */
    /* СЦЕНАРИЙ 2: Фатальный крах канала (Превышение энергетического предела)  */
    /* ------------------------------------------------------------------------- */
    printf("[ТЕСТ 2] Наносим сокрушительный удар: намертво забиваем мусором кусок пакета...\n");

    /* Стираем 40 дибитов подряд (мощный секундный всплеск помехи в эфире) */
    for (i = 200; i < 240; i++) {
        output_dibits[i] = 0x55; /* Фатальный регулярный мусор */
    }

    printf("[RX] Запуск декодера Витерби в условиях тотального забития...\n");
    viterbi_decode_block(rx_bytes, output_dibits);

    /* Верификация краха */
    if (memcmp(tx_bytes, rx_bytes, 105) != 0) {
        printf(">> [УСПЕХ] Декодер контролируемо сломался (выдал искаженные байты).\n");
        printf(">> [УСПЕХ] Итоговая метрика ушла вверх. Ложного прохода мусора нет.\n");
    } else {
        printf(">> [ПРОВАЛ] Чудес не бывает: декодер восстановил полностью стёртый кусок? Что-то не так в тесте.\n");
        success = 0;
    }

    printf("\n==============================================================================$$\n");
    if (success) {
        printf("  [ИТОГ] Сверточный конвейер полностью исследован и КАНОНИЗИРОВАН!\n");
    } else {
        printf("  [ИТОГ] Обнаружены аномалии в логике работы под помехами.\n");
    }
    printf("==============================================================================$$\n");

    return success ? 0 : 1;
}
